/**
 * Content model for Bihar Board Padhai.
 * All study content lives in /content/{class}/{medium}/{subject}/{chapter}.json
 * and is validated by `npm run content:check`. The UI never hard-codes content.
 */

export type ClassId = 'class-10' | 'class-12';
export type Medium = 'hindi' | 'english';
export type Stream = 'arts' | 'science' | 'commerce';

/** Editorial status. Only `verified_official` may ever be labelled official in the UI. */
export type ContentStatus = 'sample' | 'draft' | 'reviewed' | 'verified_official';

export interface ContentMeta {
  status: ContentStatus;
  /** Human-readable source, e.g. "Written by AR Group Ventures editorial team (sample)" */
  source: string;
  /** Link to the source (official PDF, textbook page) or empty string */
  sourceUrl: string;
  /** ISO date YYYY-MM-DD */
  lastReviewed: string;
  /** Reviewer name or role */
  reviewer: string;
}

export type NoteBlock =
  | { type: 'heading'; text: string }
  | { type: 'paragraph'; text: string }
  | { type: 'list'; items: string[] }
  | { type: 'formula'; text: string; label?: string }
  | { type: 'remember'; text: string }
  | { type: 'image'; src: string; alt: string; caption?: string };

export interface ObjectiveQuestion extends ContentMeta {
  /** Globally unique, identical across mediums, e.g. "c10-sci-ch01-q01" */
  id: string;
  question: string;
  /** Exactly four options A–D */
  options: [string, string, string, string];
  /** Index 0–3 of the correct option */
  answer: 0 | 1 | 2 | 3;
  explanation: string;
  /** Optional year if this is a previous-year question (only with a cited source) */
  year?: number;
}

export interface SubjectiveQuestion extends ContentMeta {
  id: string;
  type: 'short' | 'long';
  marks: number;
  question: string;
  /** Model answer outline: key points a student should write */
  answerOutline: string[];
}

export interface Chapter extends ContentMeta {
  /** Identical across mediums, e.g. "c10-sci-ch01" */
  id: string;
  class: ClassId;
  medium: Medium;
  subjectId: string;
  chapterNumber: number;
  /** Position in content/syllabus.json (section title + chapter number) */
  syllabus?: { section: string; no: number };
  /** URL slug in this medium's language (Hinglish for Hindi medium), e.g. "rasayanik-abhikriya" */
  slug: string;
  title: string;
  /** Search aliases: Hindi, English and Hinglish spellings */
  aliases: string[];
  /** Short one-line summary used in lists and meta descriptions */
  summary: string;
  textbook: { name: string; url: string };
  /** YouTube lesson, loaded only on tap. null when none. */
  youtube: { id: string; title: string } | null;
  notes: NoteBlock[];
  objective: ObjectiveQuestion[];
  important: SubjectiveQuestion[];
}

export interface MockTest extends ContentMeta {
  id: string;
  class: ClassId;
  medium: Medium;
  subjectId: string;
  title: string;
  /** Questions given in the paper */
  given: number;
  /** Questions the student must attempt (BSEB pattern: half of given) */
  attempt: number;
  /** Duration in minutes; BSEB full paper is 195 (3 h 15 min) */
  durationMin: number;
  /** Question ids drawn from chapter objective pools */
  questionIds: string[];
}

export interface PaperEntry {
  id: string;
  class: ClassId;
  /** Which mediums this paper serves */
  mediums: Medium[];
  subjectId: string;
  subjectCode: string;
  year: number;
  title: { hi: string; en: string };
  sourceType: 'bseb_official_model_paper' | 'previous_year' | 'sample';
  /** Shown as "Previous year (source: …)" */
  sourceLabel: string;
  url: string;
  /** Approximate file size in bytes, 0 when unknown (external page) */
  sizeBytes: number;
  external: boolean;
}

export interface ExamDate {
  class: ClassId;
  year: number;
  status: 'official' | 'expected';
  start: string;
  end: string;
  note?: string;
  sourceUrl: string;
}

export interface ExamCalendar {
  _comment: string;
  updated: string;
  exams: ExamDate[];
}

/** Lightweight entry in the generated content index (src/generated/content-index.json) */
export interface ChapterIndexEntry {
  id: string;
  class: ClassId;
  medium: Medium;
  subjectId: string;
  chapterNumber: number;
  syllabus: { section: string; no: number } | null;
  slug: string;
  title: string;
  summary: string;
  aliases: string[];
  status: ContentStatus;
  objectiveCount: number;
  importantCount: number;
  file: string;
}

/** Normalised BSEB syllabus (content/syllabus.json, generated by scripts/import-syllabus.ts) */
export interface SyllabusChapter {
  no: number;
  title: { hi: string; en: string };
  hiMissing: boolean;
  enMissing: boolean;
}
export interface SyllabusSubject {
  id: string;
  class: ClassId;
  codes: string[];
  streams: Stream[];
  name: { hi: string; en: string };
  marks: { total: number | null; theory: number | null; practical: number | null; split: string | null; objective: string | null; note: string | null };
  textbooks: string[];
  sections: Array<{ title: string; chapters: SyllabusChapter[] }>;
  chapterCount: number;
  /** official = BSEB syllabus document; textbook = NCERT book per BSEB rule; gap = chapters not yet extracted */
  status: 'verified_official' | 'verified_textbook' | 'gap';
  statusNote: string;
  note: string | null;
  sources: string[];
}
export interface Syllabus {
  meta: { session: string; generated: string; warning: string; rules: string[]; sources: Record<string, string>; importedOn: string };
  subjects: SyllabusSubject[];
}
